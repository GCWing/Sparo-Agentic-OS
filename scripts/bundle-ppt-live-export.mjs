#!/usr/bin/env node
/**
 * Bundles the Bridge-owned PPTX exporter for the latest built-in PPT Live release.
 */
import { spawnSync } from 'child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, '..');
const RELEASES_DIR = join(ROOT, 'bundles', 'product-apps', 'builtin-ppt-live');
const STAGING = join(ROOT, 'target', 'ppt-live-export-staging');

function parseSemver(value) {
  const match = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z.-]+))?(?:\+[0-9A-Za-z.-]+)?$/.exec(value);
  if (!match) return null;
  return {
    value,
    numbers: match.slice(1, 4).map(Number),
    prerelease: match[4]?.split('.') ?? null,
  };
}

function comparePrerelease(left, right) {
  if (left === null && right === null) return 0;
  if (left === null) return 1;
  if (right === null) return -1;
  const length = Math.max(left.length, right.length);
  for (let index = 0; index < length; index += 1) {
    const leftPart = left[index];
    const rightPart = right[index];
    if (leftPart === undefined) return -1;
    if (rightPart === undefined) return 1;
    if (leftPart === rightPart) continue;
    const leftNumeric = /^\d+$/.test(leftPart);
    const rightNumeric = /^\d+$/.test(rightPart);
    if (leftNumeric && rightNumeric) return Number(leftPart) - Number(rightPart);
    if (leftNumeric) return -1;
    if (rightNumeric) return 1;
    return leftPart.localeCompare(rightPart);
  }
  return 0;
}

function compareSemver(left, right) {
  for (let index = 0; index < 3; index += 1) {
    const difference = left.numbers[index] - right.numbers[index];
    if (difference !== 0) return difference;
  }
  return comparePrerelease(left.prerelease, right.prerelease);
}

function latestRelease() {
  const latest = readdirSync(RELEASES_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => parseSemver(entry.name))
    .filter(Boolean)
    .sort(compareSemver)
    .at(-1);
  if (!latest) throw new Error(`No semantic-versioned PPT Live release found under ${RELEASES_DIR}`);

  const releaseDir = join(RELEASES_DIR, latest.value);
  const manifest = JSON.parse(readFileSync(join(releaseDir, 'app.json'), 'utf8'));
  if (manifest.id !== 'builtin-ppt-live' || manifest.version !== latest.value) {
    throw new Error(`PPT Live release identity mismatch at ${releaseDir}`);
  }
  return { releaseDir, version: latest.value };
}

function run(command, args, cwd) {
  const env = { ...process.env };
  delete env.NODE_PATH;
  const result = spawnSync(command, args, {
    cwd,
    stdio: 'inherit',
    env,
    shell: process.platform === 'win32',
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function main() {
  const release = latestRelease();
  const bridgeSource = join(
    release.releaseDir,
    'components',
    'bridges',
    'builtin-ppt-runtime',
    'source',
  );
  const canonicalEntry = join(bridgeSource, 'src', 'export', 'pptx-export.mjs');
  const output = join(bridgeSource, 'src', 'vendor', 'ppt-export.bundle.mjs');
  const stagingEntry = join(STAGING, 'src', 'pptx-export.mjs');
  const rawOutput = join(STAGING, 'ppt-export.bundle.raw.mjs');

  console.log(`[bundle-ppt-live-export] using builtin-ppt-live@${release.version}`);
  rmSync(STAGING, { recursive: true, force: true });
  mkdirSync(dirname(stagingEntry), { recursive: true });
  cpSync(canonicalEntry, stagingEntry);
  writeFileSync(join(STAGING, 'package.json'), `${JSON.stringify({
    name: 'ppt-live-export-bundle',
    private: true,
    type: 'module',
    dependencies: { pptxgenjs: '^4.0.1' },
    devDependencies: { esbuild: '0.25.0' },
  }, null, 2)}\n`);

  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  run(npm, ['install', '--no-audit', '--no-fund'], STAGING);
  const esbuild = join(
    STAGING,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? 'esbuild.cmd' : 'esbuild',
  );
  run(esbuild, [
    stagingEntry,
    '--bundle',
    '--format=esm',
    '--platform=browser',
    '--target=es2020',
    `--outfile=${rawOutput}`,
    '--log-level=warning',
  ], STAGING);

  mkdirSync(dirname(output), { recursive: true });
  const banner = '/* Generated by scripts/bundle-ppt-live-export.mjs. Do not edit. */\n';
  writeFileSync(output, banner + readFileSync(rawOutput, 'utf8'));
  const size = readFileSync(output).length;
  if (size < 400_000) throw new Error(`PPT Live export bundle is unexpectedly small: ${size} bytes`);

  rmSync(STAGING, { recursive: true, force: true });
  console.log(`[bundle-ppt-live-export] wrote ${output}`);
}

main();
