#!/usr/bin/env node
/**
 * Bundles pptxgenjs, pdf-lib, and jszip with PPT Live export logic for the Live App WebView.
 * Output is committed under bundles/live-apps/ppt-live/src/vendor/ — no Node/Bun at runtime.
 */
import { spawnSync } from 'child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const BUNDLE_DIR = join(ROOT, 'bundles', 'live-apps', 'ppt-live');
const STAGING = join(ROOT, 'target', 'ppt-live-export-staging');
const OUT = join(BUNDLE_DIR, 'src', 'vendor', 'ppt-export.bundle.mjs');
const SKILL_CLI_OUT = join(
  BUNDLE_DIR,
  'skills',
  'ppt-design',
  'scripts',
  'skill-export-pptx.bundle.cjs',
);

const PKG = {
  name: 'ppt-live-export-bundle',
  private: true,
  type: 'module',
  dependencies: {
    'pptxgenjs': '^4.0.1',
    'pdf-lib': '^1.17.1',
    'jszip': '^3.10.1',
    'jsdom': '^25.0.0',
  },
  devDependencies: {
    esbuild: '0.25.0',
  },
};

const SKILL_PKG = {
  name: 'ppt-live-skill-export-bundle',
  private: true,
  type: 'commonjs',
  dependencies: {
    'pptxgenjs': '^4.0.1',
    'jsdom': '^25.0.0',
  },
  devDependencies: {
    esbuild: '0.25.0',
  },
};

function bundleEnv() {
  const env = { ...process.env };
  // Broken NODE_PATH (e.g. pointing at a node binary) breaks esbuild resolution.
  delete env.NODE_PATH;
  return env;
}

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, {
    cwd,
    stdio: 'inherit',
    env: bundleEnv(),
    shell: process.platform === 'win32',
  });
  if (r.error) {
    console.error(`[bundle-ppt-live-export] failed to run ${cmd}: ${r.error.message}`);
    process.exit(1);
  }
  if (r.status !== 0) process.exit(r.status ?? 1);
}

function syncSkillHtml2PptxDomCore() {
  const src = join(BUNDLE_DIR, 'src', 'html2pptx-dom-core.js');
  const out = join(BUNDLE_DIR, 'skills', 'ppt-design', 'scripts', 'html2pptx-dom-core.cjs');
  let body = readFileSync(src, 'utf8');
  body = `/** Synced from ../../src/html2pptx-dom-core.js — do not edit by hand. */\n${body}`
    .replace(/^export const /gm, 'const ')
    .replace(/^export function /gm, 'function ');
  writeFileSync(
    out,
    `${body}\nmodule.exports = {\n  PT_PER_PX,\n  PX_PER_IN,\n  measureBodyDimensions,\n  extractSlideDataFromDocument,\n};\n`,
  );
}

function copyExportSources(targetSrc) {
  const names = [
    'export-bundle-entry.mjs',
    'export-deck-browser.js',
    'pptx-html-build.js',
    'pptx-element-export.js',
  ];
  mkdirSync(targetSrc, { recursive: true });
  for (const name of names) {
    cpSync(join(BUNDLE_DIR, 'src', name), join(targetSrc, name));
  }
}

function main() {
  syncSkillHtml2PptxDomCore();

  rmSync(STAGING, { recursive: true, force: true });
  mkdirSync(STAGING, { recursive: true });
  const stagingSrc = join(STAGING, 'src');
  copyExportSources(stagingSrc);
  writeFileSync(join(STAGING, 'package.json'), `${JSON.stringify(PKG, null, 2)}\n`);

  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  run(npm, ['install', '--no-audit', '--no-fund'], STAGING);

  const esbuildBin = join(STAGING, 'node_modules', '.bin', process.platform === 'win32' ? 'esbuild.cmd' : 'esbuild');
  const entry = join(stagingSrc, 'export-bundle-entry.mjs');
  mkdirSync(dirname(OUT), { recursive: true });

  run(esbuildBin, [
    entry,
    '--bundle',
    '--format=esm',
    '--platform=browser',
    '--target=es2020',
    `--outfile=${OUT}`,
    '--log-level=warning',
  ], STAGING);

  const banner = '/* PPT Live export runtime — generated by scripts/bundle-ppt-live-export-browser.mjs; do not edit. */\n';
  writeFileSync(OUT, banner + readFileSync(OUT, 'utf8'));

  const size = readFileSync(OUT).length;
  if (size < 500_000) {
    console.error(`[bundle-ppt-live-export] output too small (${size} bytes); bundle may be broken`);
    process.exit(1);
  }

  rmSync(STAGING, { recursive: true, force: true });
  rmSync(join(BUNDLE_DIR, '.export-bundle-tmp'), { recursive: true, force: true });
  console.log(`[bundle-ppt-live-export] wrote ${OUT}`);

  bundleSkillExportCli();
}

function bundleSkillExportCli() {
  const staging = join(ROOT, 'target', 'ppt-live-skill-export-staging');
  const scriptsDir = join(staging, 'scripts');
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(scriptsDir, { recursive: true });

  const skillScripts = join(BUNDLE_DIR, 'skills', 'ppt-design', 'scripts');
  cpSync(join(skillScripts, 'html2pptx.cjs'), join(scriptsDir, 'html2pptx.cjs'));
  cpSync(join(skillScripts, 'html2pptx-dom-core.cjs'), join(scriptsDir, 'html2pptx-dom-core.cjs'));
  cpSync(join(skillScripts, 'skill-export-pptx-entry.cjs'), join(scriptsDir, 'skill-export-pptx-entry.cjs'));
  writeFileSync(join(staging, 'package.json'), `${JSON.stringify(SKILL_PKG, null, 2)}\n`);

  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  run(npm, ['install', '--no-audit', '--no-fund'], staging);

  const esbuildBin = join(
    staging,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? 'esbuild.cmd' : 'esbuild',
  );
  const entry = join(scriptsDir, 'skill-export-pptx-entry.cjs');
  mkdirSync(dirname(SKILL_CLI_OUT), { recursive: true });

  run(esbuildBin, [
    entry,
    '--bundle',
    '--format=cjs',
    '--platform=node',
    '--target=node18',
    `--outfile=${SKILL_CLI_OUT}`,
    '--log-level=warning',
  ], staging);

  const banner = '/* PPT Live skill CLI export — generated by scripts/bundle-ppt-live-export-browser.mjs; do not edit. */\n';
  writeFileSync(SKILL_CLI_OUT, banner + readFileSync(SKILL_CLI_OUT, 'utf8'));

  const skillSize = readFileSync(SKILL_CLI_OUT).length;
  if (skillSize < 500_000) {
    console.error(`[bundle-ppt-live-export] skill CLI bundle too small (${skillSize} bytes)`);
    process.exit(1);
  }

  rmSync(staging, { recursive: true, force: true });
  console.log(`[bundle-ppt-live-export] wrote ${SKILL_CLI_OUT}`);
}

main();
